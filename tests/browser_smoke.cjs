// Optional developer test: requires Playwright + Chromium, not needed to run the app.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true,executablePath:process.env.SAMY_CHROMIUM_PATH || undefined});
  try {
  const page = await browser.newPage({viewport:{width:1920,height:1080}});
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  await page.goto('http://127.0.0.1:8099/tv/');
  await page.waitForSelector('.app-card');
  assert.equal(await page.locator('.app-card').count(),14);
  assert.equal(await page.locator('.catalog-group').count(),2);
  assert.equal(await page.locator('html').getAttribute('lang'),'en');
  assert.equal(await page.locator('html').getAttribute('dir'),'ltr');
  assert.equal(await page.evaluate(()=>getComputedStyle(document.body).direction),'ltr');
  assert.equal(await page.locator('[data-nav-filter=all]').innerText(),'For you');
  assert.equal(await page.locator('[data-nav-filter=native]').innerText(),'Apps');
  assert.doesNotMatch(await page.locator('body').innerText(),/[\u0600-\u06ff]/);
  await page.waitForFunction(()=>document.querySelector('#notice').classList.contains('quiet') && parseFloat(getComputedStyle(document.querySelector('#notice')).opacity) < 0.01);
  assert.equal((await page.locator('#browse-apps').innerText()).replace(/\s+/g,' '),'Browse apps →');
  await page.screenshot({path:'artifacts/tv-desktop.png',fullPage:true});
  await page.screenshot({path:'artifacts/tv-screen-1080.png'});
  await page.locator('#remote-check').click();
  assert.equal(await page.locator('#remote-panel').isVisible(),true);
  await page.locator('#browse-apps').focus();
  for (const key of ['ArrowDown','ArrowLeft','ArrowUp','ArrowRight']) await page.keyboard.press(key);
  await page.locator('#browse-apps').focus();
  await page.keyboard.press('Enter');
  await page.keyboard.press('Escape');
  assert.match(await page.locator('#remote-counts').innerText(),/Arrows: 4 \/ 4 · OK: 1 · Back: 1/);
  await page.locator('#browse-apps').focus();
  await page.keyboard.press('Backspace');
  assert.match(await page.locator('#remote-counts').innerText(),/Back: 2/);
  assert.match(await page.locator('#remote-panel small').innerText(),/not proof/);
  await page.screenshot({path:'artifacts/remote-check.png'});
  await page.locator('#remote-reset').click();
  assert.match(await page.locator('#remote-counts').innerText(),/Arrows: 0 \/ 4 · OK: 0 · Back: 0/);
  await page.locator('#remote-close').click();
  assert.equal(await page.locator('#remote-panel').isVisible(),false);
  await page.locator('#search').fill('Netflix');
  assert.equal(await page.locator('.app-card').count(),1);
  await page.locator('.favorite').click();
  await page.reload(); await page.waitForSelector('.app-card');
  await page.locator('[data-filter="favorites"]').click();
  assert.equal(await page.locator('.app-card').count(),1);
  assert.match(await page.locator('.app-title').innerText(),/Netflix/);
  await page.locator('.app-launch').click();
  assert.match(await page.locator('#notice').innerText(),/Mac/);
  await page.locator('[data-filter="all"]').click();
  await page.locator('.app-launch').first().focus();
  await page.keyboard.press('ArrowLeft');
  assert.equal(await page.evaluate(()=>document.activeElement.tagName),'BUTTON');
  await page.evaluate(() => document.dispatchEvent(new KeyboardEvent('keydown', {key:'Unidentified',keyCode:40,bubbles:true})));
  assert.equal(await page.evaluate(()=>document.activeElement.tagName),'BUTTON');
  await page.locator('#search').fill('no-such-app');
  assert.equal(await page.locator('.app-card').count(),0);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.app-card').count(),14);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.ok(await page.locator('.watchfree-actions .button').first().evaluate(e=>e.getBoundingClientRect().width>=150));
  await page.waitForFunction(()=>document.querySelector('#notice').classList.contains('quiet') && parseFloat(getComputedStyle(document.querySelector('#notice')).opacity) < 0.01);
  await page.screenshot({path:'artifacts/tv-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:8099/tv/');
  await page.evaluate(() => { window.location.href = 'http://127.0.0.1:8766/'; });
  await page.waitForURL('http://127.0.0.1:8766/'); await page.waitForSelector('.app-card');
  await page.waitForFunction(()=>document.querySelector('#connection').textContent.includes('Offline preview'));
  await page.locator('[data-key="volume_up"]').click();
  assert.match(await page.locator('#notice').innerText(),/Offline preview/);
  await page.locator('#control summary').click();
  await page.locator('#check-reachability').click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('No page request'));
  await page.screenshot({path:'artifacts/mac-controller.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: English LTR desktop/mobile UI; 14 catalog entries; search; persistent favorites; TV native-action restriction; arrow navigation; remote-event counters; Escape; mobile overflow; offline command rejection; diagnostics; no browser exceptions. No real TV used.');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
